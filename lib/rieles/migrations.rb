module Rieles
  # db/migrate/<version>_<name>.rb, Rails style. Each migration's `change`
  # is read at build time into SQL; the binary applies pending versions at
  # boot. Replaying them in order also gives the schema, which
  # `rieles db:migrate` writes to db/schema.rb.
  class Migrations
    Migration = Struct.new(:version, :name, :statements)

    attr_reader :migrations, :tables, :indexes

    def initialize(dir)
      @dir = dir
      @tables = {}
      @indexes = []
      @migrations = Dir[File.join(dir, "*.rb")].sort.map { |file| read(file) }
    end

    def any? = @migrations.any?

    def schema_rb
      version = @migrations.last&.version || "0"
      body = @tables.values.map do |t|
        cols = t.columns.reject { |c| c.name == "id" }
        stamps = %w[created_at updated_at].all? { |n| cols.any? { |c| c.name == n } }
        lines = cols.reject { |c| stamps && c.timestamp? }.map { |c| "    t.#{schema_type(c)} :#{c.name}#{column_options(c)}" }
        lines << "    t.timestamps" if stamps
        "  create_table :#{t.name} do |t|\n#{lines.join("\n")}\n  end\n"
      end
      index_lines = @indexes.map { |i| "  add_index :#{i[:table]}, #{i[:columns].map(&:to_sym).inspect}#{i[:unique] ? ', unique: true' : ''}\n" }
      "# Generated by `rieles db:migrate` from db/migrate. Do not edit.\n" \
        "Rieles::Schema.define(version: #{version}) do\n#{(body + index_lines).join("\n")}end\n"
    end

    private

    def read(file)
      base = File.basename(file, ".rb")
      version, name = base.split("_", 2)
      raise CompileError, "#{file}: expected <version>_<name>.rb" unless version.match?(/\A\d+\z/) && name
      root = Rieles.parse(File.read(file), file)
      klass = root.statements.body.find { |n| n.is_a?(Prism::ClassNode) } or raise CompileError, "#{file}: expected a class"
      change = (klass.body&.body || []).find { |n| n.is_a?(Prism::DefNode) && n.name == :change } or
        raise CompileError, "#{file}: migrations define `change`"
      @file = file
      statements = (change.body&.body || []).flat_map { |stmt| operation(stmt) }
      Migration.new(version, name, statements)
    end

    def operation(node)
      fail!(node, "unsupported migration statement") unless node.is_a?(Prism::CallNode) && node.receiver.nil?
      args, kw = Rieles.call_args(node)
      lit = ->(n) { Rieles.literal(n) }
      case node.name
      when :create_table then create_table(node)
      when :drop_table
        name = lit.(args[0]).to_s
        @tables.delete(name)
        ["DROP TABLE #{name}"]
      when :add_column
        table = table!(node, lit.(args[0]))
        column = column(lit.(args[1]).to_s, lit.(args[2]), kw)
        table.columns << column
        [table.add_column_sql(column)]
      when :add_reference, :add_belongs_to
        table = table!(node, lit.(args[0]))
        column = column("#{lit.(args[1])}_id", :references, kw)
        table.columns << column
        [table.add_column_sql(column)]
      when :remove_column
        table = table!(node, lit.(args[0]))
        name = lit.(args[1]).to_s
        table.columns.reject! { |c| c.name == name }
        ["ALTER TABLE #{table.name} DROP COLUMN #{name}"]
      when :rename_column
        table = table!(node, lit.(args[0]))
        from, to = lit.(args[1]).to_s, lit.(args[2]).to_s
        table.column(from)&.name = to
        ["ALTER TABLE #{table.name} RENAME COLUMN #{from} TO #{to}"]
      when :rename_table
        from, to = lit.(args[0]).to_s, lit.(args[1]).to_s
        table = @tables.delete(from) or fail!(node, "no table #{from}")
        table.name = to
        @tables[to] = table
        ["ALTER TABLE #{from} RENAME TO #{to}"]
      when :add_index
        index = { table: lit.(args[0]).to_s, columns: Array(lit.(args[1])).map(&:to_s), unique: kw[:unique] && lit.(kw[:unique]) }
        @indexes << index
        [Schema.index_sql(index)]
      when :remove_index
        table = lit.(args[0]).to_s
        cols = Array(kw[:column] ? lit.(kw[:column]) : lit.(args[1])).map(&:to_s)
        @indexes.reject! { |i| i[:table] == table && i[:columns] == cols }
        ["DROP INDEX IF EXISTS #{Schema.index_name(table, cols)}"]
      when :execute then [lit.(args[0]).to_s]
      else fail!(node, "unsupported migration method #{node.name}")
      end
    end

    def create_table(node)
      table = Schema.table_from(node, @file)
      @tables[table.name] = table
      [table.create_sql.sub("CREATE TABLE IF NOT EXISTS", "CREATE TABLE")]
    end

    def column(name, type, kw)
      opts = kw.transform_values { |v| Rieles.literal(v) }
      kind = Schema::TYPES.fetch(type.to_sym) { raise CompileError, "#{@file}: unsupported column type #{type}" }
      Column.new(name, kind, opts[:default], opts[:null] == true)
    end

    def table!(node, name)
      @tables[name.to_s] or fail!(node, "no table #{name} (created by an earlier migration?)")
    end

    def schema_type(column)
      { integer: "integer", boolean: "boolean", float: "float", string: "string" }.fetch(column.type)
    end

    def column_options(column)
      opts = []
      opts << "default: #{column.default.inspect}" unless column.default.nil?
      opts << "null: true" if column.null
      opts.empty? ? "" : ", #{opts.join(', ')}"
    end

    def fail!(node, message)
      raise CompileError, "#{@file}:#{node.location.start_line}: #{message}"
    end
  end
end
