module Rieles
  # Reads an app laid out like a Rails app and writes one tep source file
  # (Sinatra-style DSL plus plain classes) that `tep build` compiles.
  class Build
    Template = Struct.new(:path, :dir, :name) do
      def partial? = name.start_with?("_")
      def layout? = dir == "layouts"
      def key = "#{dir}/#{name}"
      def method_name
        return "layout_#{name}" if layout?
        "#{partial? ? 'partial' : 'view'}_#{dir.tr('/', '_')}_#{name.delete_prefix('_')}"
      end
    end

    # What the lowering needs to resolve render calls from one file.
    class Context
      attr_reader :dir

      def initialize(build, dir, view:)
        @build = build
        @dir = dir
        @view = view
      end

      def view? = @view
      def template_method(key) = @build.templates[key]&.method_name

      def partial_method(key, locals, where)
        @build.use_partial(key, locals, where)
      end
    end

    attr_reader :templates

    def initialize(app_dir)
      @app = File.expand_path(app_dir)
      @partial_locals = {}
    end

    def routes = @routes ||= Routes.new(path("config/routes.rb"))

    def write(out_dir)
      FileUtils.rm_rf(out_dir)
      FileUtils.mkdir_p(out_dir)
      assets = path("app/assets")
      FileUtils.cp_r(assets, File.join(out_dir, "assets")) if Dir.exist?(assets)
      out = File.join(out_dir, "app.rb")
      File.write(out, generate)
      out
    end

    def use_partial(key, locals, where)
      template = @templates[key] or raise CompileError, "#{where}: missing partial app/views/#{key}.html.erb"
      known = @partial_locals[key]
      if known && known != locals
        raise CompileError, "#{where}: #{key} is rendered with locals #{locals.inspect} here and #{known.inspect} elsewhere"
      end
      @partial_locals[key] = locals
      template.method_name
    end

    private

    def path(rel) = File.join(@app, rel)
    def rel(file) = file.delete_prefix("#{@app}/")

    def generate
      schema = Schema.new(path("db/schema.rb"))
      @templates = Dir[path("app/views/**/*.html.erb")].to_h do |file|
        key = rel(file).delete_prefix("app/views/").delete_suffix(".html.erb")
        [key, Template.new(file, File.dirname(key), File.basename(key))]
      end
      controllers = load_controllers
      views = compile_views(controllers)

      [
        "# Generated by rieles from #{File.basename(@app)}. Do not edit.",
        "require 'sinatra'",
        # The default prefork server ignores SIGINT while a keep-alive
        # connection is idle (OriPekelman/tep#277).
        "set :scheduler, :scheduled",
        File.read(RUNTIME),
        application_record,
        *Dir[path("app/models/*.rb")].sort.reject { |f| f.end_with?("/application_record.rb") }.map { |f| Model.new(f, schema).to_ruby },
        controllers.fetch("ApplicationController")[:source],
        *controllers.reject { |name, _| name == "ApplicationController" }.values.map { |c| c[:source] },
        application_controller_support,
        *views,
        schema_setup(schema),
        *routes.routes.map { |r| route_block(r, controllers) },
        not_found_block
      ].join("\n")
    end

    def application_record
      file = path("app/models/application_record.rb")
      File.exist?(file) ? File.read(file) : "class ApplicationRecord < Rieles::Record\nend\n"
    end

    def load_controllers
      controllers = {}
      Dir[path("app/controllers/*_controller.rb")].sort.each do |file|
        dir = File.basename(file, "_controller.rb")
        name = "#{Inflector.camelize(dir)}Controller"
        source = File.read(file)
        klass = Rieles.parse(source, rel(file)).statements.body.find { |n| n.is_a?(Prism::ClassNode) }
        unless klass&.constant_path&.slice == name
          raise CompileError, "#{rel(file)}: expected class #{name}"
        end
        actions = (klass.body&.body || []).grep(Prism::DefNode).map { |d| d.name.to_s }
        lowered = Lowering.lower(source, rel(file), Context.new(self, dir, view: false))
        controllers[name] = { dir: dir, actions: actions, source: lowered }
      end
      controllers["ApplicationController"] ||= {
        dir: "application", actions: [], source: "class ApplicationController < Rieles::Controller\nend\n"
      }
      controllers
    end

    def compile_views(controllers)
      by_class = Hash.new { |h, k| h[k] = [] }
      @templates.each_value do |t|
        owner = if t.partial? || t.layout? then "ApplicationController"
                else "#{Inflector.camelize(t.dir)}Controller"
                end
        unless controllers.key?(owner)
          raise CompileError, "#{rel(t.path)}: no #{owner} for this template"
        end
        signature = t.layout? ? "#{t.method_name}(content)" : "#{t.method_name}__SIGNATURE__"
        ruby = Erb.compile(File.read(t.path), signature, layout: t.layout?)
        lowered = Lowering.lower(ruby, rel(t.path), Context.new(self, t.dir, view: true))
        by_class[owner] << [t, lowered]
      end
      by_class.map do |owner, defs|
        methods = defs.map do |t, ruby|
          params = t.partial? ? @partial_locals.fetch(t.key, []) : []
          ruby.sub("__SIGNATURE__", params.empty? ? "" : "(#{params.join(', ')})")
        end
        "class #{owner}\n#{methods.join("\n").gsub(/^(?=.)/, '  ')}end\n"
      end
    end

    def application_controller_support
      layout = @templates["layouts/application"]
      helpers = routes.helpers.map do |name, (param, expr)|
        "  def #{name}#{param ? "(#{param})" : ''}\n    #{expr}\n  end"
      end
      <<~RUBY
        class ApplicationController
          def render_view(html, status)
            render_html(#{layout ? "#{layout.method_name}(html)" : 'html'}, status)
          end

          def render_error(status, message)
            render_view("<h1>" + status.to_s + "</h1><p>" + h(message) + "</p>", status)
          end

        #{helpers.join("\n\n")}
        end
      RUBY
    end

    def schema_setup(schema)
      statements = schema.tables.values.map { |t| "  db.exec(#{t.create_sql.inspect})" }
      "on_start do\n  db = Rieles.connect\n#{statements.join("\n")}\n  db.close\nend\n"
    end

    def route_block(route, controllers)
      klass = "#{Inflector.camelize(route.controller)}Controller"
      controller = controllers[klass] or raise CompileError, "config/routes.rb: no #{klass} for #{route.path}"
      unless controller[:actions].include?(route.action)
        raise CompileError, "config/routes.rb: #{klass}##{route.action} is not defined"
      end
      template = @templates["#{route.controller}/#{route.action}"]
      implicit = if template
                   "c.render_view(c.#{template.method_name}, 200) unless c.performed?"
                 else
                   "c.render_error(500, \"Missing template #{route.controller}/#{route.action}\") unless c.performed?"
                 end
      <<~RUBY
        #{route.verb} #{route.path.inspect} do
          puts req.verb + " " + req.path + " -> #{klass}##{route.action}"
          c = #{klass}.new(req, res)
          begin
            c.#{route.action}
            #{implicit}
          rescue Rieles::RecordNotFound => e
            c.render_error(404, "Not found")
          rescue StandardError => e
            puts "  " + e.class.name + ": " + e.message
            c.render_error(500, "Something went wrong")
          end
          c.response_body
        end
      RUBY
    end

    def not_found_block
      <<~RUBY
        not_found do
          c = ApplicationController.new(req, res)
          c.render_error(404, "Not found")
          c.response_body
        end
      RUBY
    end
  end
end
